#!/usr/bin/env node
// Writes indexer/config.yaml from shared/addresses.{testnet,mainnet}.json so the
// indexer never carries its own copy of contract addresses.
//
//   node scripts/gen-config.mjs           placeholders allowed (local dev, tests)
//   node scripts/gen-config.mjs --strict  fails unless every chain has real v2 addresses (deploy)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');

// Stand-ins until Task 6 writes oracle / guardianV2 / deployBlockV2. They hold no code on
// either chain, so an indexer built from them indexes nothing from these contracts.
export const PLACEHOLDER_ORACLE = '0x00000000000000000000000000000000000a11ce';
export const PLACEHOLDER_GUARDIAN = '0x00000000000000000000000000000000000b0b00';

const CHAINS = [
  { network: 'testnet', id: 10143 },
  { network: 'mainnet', id: 143 },
];

/** Resolves one chain's addresses, falling back to placeholders where v2 is not deployed yet. */
export function resolveChain(network, file) {
  const missing = [];
  const oracle = file.oracle ?? (missing.push('oracle'), PLACEHOLDER_ORACLE);
  const guardian = file.guardianV2 ?? (missing.push('guardianV2'), PLACEHOLDER_GUARDIAN);
  const startBlock = file.deployBlockV2 ?? (missing.push('deployBlockV2'), 0);
  let vaults = (file.vaults ?? []).map((v) => v.address);
  if (!file.vaults) {
    missing.push('vaults');
    // Testnet mirrors predate v2 and stay the testnet vaults; mainnet has no fallback.
    if (network === 'testnet') vaults = (file.mirrors ?? []).map((m) => m.address);
  }
  return { oracle, guardian, startBlock: Number(startBlock), vaults, missing };
}

export function renderConfig(chains) {
  const lines = [
    '# yaml-language-server: $schema=./node_modules/envio/evm.schema.json',
    '# GENERATED by scripts/gen-config.mjs from shared/addresses.*.json. Do not edit by hand.',
    'name: tare-indexer',
    'description: Tare risk oracle verdicts, GuardianV2 protections and exits, and ERC-4626 vault flows',
    'field_selection:',
    '  transaction_fields:',
    '    - hash',
    'contracts:',
    '  - name: TareRiskOracle',
    '    events:',
    '      - event: VerdictPosted(uint256 indexed id, address indexed vault, uint8 verdict, uint16 confidenceBps, uint16 riskBps, bytes32 stateHash, uint64 postedAt)',
    '      - event: VerdictResolved(uint256 indexed id, bool adverse, uint8 reasons)',
    '  - name: GuardianV2',
    '    events:',
    '      - event: Enabled(address indexed owner, address indexed vault, uint16 minConfidenceBps, uint32 maxAge)',
    '      - event: Disabled(address indexed owner, address indexed vault)',
    '      - event: Exited(address indexed owner, address indexed vault, uint256 indexed verdictId, address caller, uint256 shares, uint256 assets, uint256 remainingShares)',
    '  - name: ERC4626Vault',
    '    events:',
    '      - event: Deposit(address indexed sender, address indexed owner, uint256 assets, uint256 shares)',
    '      - event: Withdraw(address indexed sender, address indexed receiver, address indexed owner, uint256 assets, uint256 shares)',
    'chains:',
  ];
  for (const c of chains) {
    lines.push(
      `  - id: ${c.id} # Monad ${c.network}${c.missing.length ? ` (placeholders: ${c.missing.join(', ')})` : ''}`,
      `    start_block: ${c.startBlock}`,
      '    contracts:',
      '      - name: TareRiskOracle',
      `        address: "${c.oracle}"`,
      '      - name: GuardianV2',
      `        address: "${c.guardian}"`,
    );
    if (c.vaults.length) {
      lines.push('      - name: ERC4626Vault', '        address:');
      for (const v of c.vaults) lines.push(`          - "${v}"`);
    }
  }
  return lines.join('\n') + '\n';
}

function main() {
  const strict = process.argv.includes('--strict');
  const chains = CHAINS.map(({ network, id }) => {
    const file = JSON.parse(readFileSync(join(root, 'shared', `addresses.${network}.json`), 'utf8'));
    return { network, id, ...resolveChain(network, file) };
  });
  const gaps = chains.filter((c) => c.missing.length);
  for (const c of gaps) console.warn(`[gen-config] ${c.network}: placeholder for ${c.missing.join(', ')}`);
  if (strict && gaps.length) {
    console.error('[gen-config] --strict: v2 addresses missing, refusing to write a deployable config');
    process.exit(1);
  }
  writeFileSync(join(here, '..', 'config.yaml'), renderConfig(chains));
  console.log('[gen-config] wrote indexer/config.yaml');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
